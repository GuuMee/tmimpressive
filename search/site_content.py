def search_pages(query):
    """Ищем страницы по названию, описанию и ключевым словам."""
    q = query.lower()
    found = []
    for page in PAGES:
        haystack = ' '.join([
            page['title'].lower(),
            page['description'].lower(),
            page['keywords'],
        ])
        if q in haystack:
            found.append(page)
    return found